    }

    private string ExpressionAsType(ExpressionSyntax expression) => expression switch
    {
        NameExpressionSyntax name => TypeNameText(name.Name),
        MemberAccessExpressionSyntax member => $"{ExpressionAsType(member.Target)}.{Identifier(member.MemberName)}",
        LiteralExpressionSyntax { Value: string text } => TypeNameText(text),
        _ => EmitExpression(expression),
    };

    private string EmitParameter(ParameterSyntax parameter)
    {
        bool isParams = parameter.Modifiers.HasFlag(ParameterModifiers.Params);
        string prefix = isParams
            ? "params "
            : parameter.Modifiers.HasFlag(ParameterModifiers.Out)
                ? "out "
                : parameter.Modifiers.HasFlag(ParameterModifiers.ByReference) ? "ref " : string.Empty;
        bool optional = parameter.Modifiers.HasFlag(ParameterModifiers.Optional);
        string type = isParams
            ? TypeText(parameter.Type with { IsArray = false }) + "[]"
            : TypeText(parameter.Type, parameter.Modifiers.HasFlag(ParameterModifiers.Array));
        if (optional)
            type = $"global::EPLab.Runtime.EOptional<{type}>";
        string defaultValue = optional
            ? $" = {(parameter.DefaultValue is null ? "default" : EmitExpression(parameter.DefaultValue))}"
            : parameter.DefaultValue is null ? string.Empty : $" = {EmitExpression(parameter.DefaultValue)}";
        return $"{prefix}{type} {Identifier(parameter.Name)}{defaultValue}";
    }

    private string EmitInitializer(TypeSyntax type, ArrayShapeSyntax? shape, ExpressionSyntax? initializer)
    {
        if (initializer is not null)
        {
            if (initializer is ArrayLiteralExpressionSyntax array && (shape is not null || type.IsArray))
                return $" = {EmitArrayLiteral(array, TypeText(type with { IsArray = false }))}";
            return $" = unchecked(({TypeText(type, shape is not null)})({EmitExpression(initializer)}))";
        }
        if (shape is not null || type.IsArray)
        {
            string elementType = TypeText(type with { IsArray = false });
            string dimensions = shape is null || shape.Dynamic
                ? string.Empty
                : string.Join(", ", shape.Dimensions.Select(EmitExpression));
            return $" = new global::EPLab.Runtime.EArray<{elementType}>({dimensions})";
        }
        string mapped = TypeText(type);
        if (mapped == "string")
            return " = string.Empty";
        if (mapped == "byte[]")
            return " = global::System.Array.Empty<byte>()";
        if (mapped == "global::System.DateTime")
            return " = global::EPLab.Runtime.EplRuntime.DefaultDateTime";
        if (program.Classes.ContainsKey(type.Text))
            return " = default!";
        return " = default";
    }

    private string EmitExpressionForDestination(TypeSyntax? destinationType, ExpressionSyntax expression)
    {
        if (destinationType is not null && destinationType.IsArray && expression is ArrayLiteralExpressionSyntax array)
            return EmitArrayLiteral(array, TypeText(destinationType with { IsArray = false }));
        return EmitExpression(expression);
    }

    private string EmitArrayLiteral(ArrayLiteralExpressionSyntax array, string? elementType = null)
    {
        string generic = elementType is null ? string.Empty : $"<{elementType}>";
        if (array.Items.Count == 0 && elementType is null)
            return "new global::EPLab.Runtime.EArray<object>()";
        return $"global::EPLab.Runtime.EplRuntime.Array{generic}({string.Join(", ", array.Items.Select(EmitExpression))})";
    }

    private string TypeText(TypeSyntax type, bool forceEArray = false)
    {
        string core = TypeNameText(type.Text);
        if ((type.IsArray || forceEArray) && !core.EndsWith("[]", StringComparison.Ordinal))
            core = $"global::EPLab.Runtime.EArray<{core}>";
        if (type.IsNullable && core is not "string" and not "object" && !core.EndsWith("[]", StringComparison.Ordinal))
            core += "?";
        return core;
    }

    private string TypeNameText(string value)
