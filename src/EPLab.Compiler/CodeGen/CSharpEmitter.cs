            "短整数型" or "SHORT" or "INT16" => "short",
            "整数型" or "INT" or "INT32" => "int",
            "无符号整数型" or "UINT" or "UINT32" => "uint",
            "长整数型" or "LONG" or "INT64" => "long",
            "小数型" or "FLOAT" or "SINGLE" => "float",
            "双精度小数型" or "DOUBLE" => "double",
            "逻辑型" or "BOOL" or "BOOLEAN" => "bool",
            "文本型" or "STRING" => "string",
