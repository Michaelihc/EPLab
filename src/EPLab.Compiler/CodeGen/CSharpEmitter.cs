    private static bool DefinitelyReturns(IReadOnlyList<StatementSyntax> statements)
    {
        if (statements.Count == 0)
            return false;
        StatementSyntax last = statements[^1];
        if (last is ExpressionStatementSyntax { Expression: CallExpressionSyntax { Target: NameExpressionSyntax name } }
            && name.Name.Equals("返回", StringComparison.OrdinalIgnoreCase))
            return true;
        return last is IfStatementSyntax conditional
            && conditional.ElseStatements.Count > 0
            && DefinitelyReturns(conditional.ThenStatements)
            && DefinitelyReturns(conditional.ElseStatements);
    }

