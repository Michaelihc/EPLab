using System.Globalization;
using System.Text;
using EPLab.Compiler.Semantics;
using EPLab.Compiler.Syntax;

namespace EPLab.Compiler.CodeGen;

public sealed record GeneratedSource(string FileName, string Text);

public sealed class CSharpEmitter
{
    private readonly BoundProgram program;
    private int generatedName;
    private ClassDeclarationSyntax? currentClass;
    private MethodDeclarationSyntax? currentMethod;
    private IReadOnlyDictionary<string, string> hoistedLocals = new Dictionary<string, string>();

    public CSharpEmitter(BoundProgram program) => this.program = program;

    public IReadOnlyList<GeneratedSource> Emit()
    {
        List<GeneratedSource> sources = new()
        {
            new GeneratedSource("EPLab.Runtime.g.cs", EmitRuntime()),
            new GeneratedSource("EPLab.Program.g.cs", EmitProgram()),
        };
        if (program.Plugin is not null)
            sources.Add(new GeneratedSource("EPLab.LabApi.g.cs", EmitLabApiHost()));
        return sources;
    }

    private string EmitProgram()
    {
        IndentedWriter writer = new();
        writer.WriteLine("// <auto-generated by EPLab />");
        writer.WriteLine("#nullable enable");
        foreach (string import in DefaultImports.Concat(program.NamespaceImports).Distinct(StringComparer.Ordinal))
            writer.WriteLine($"using {NormalizeQualifiedName(import)};");
        writer.WriteLine($"using static {NormalizeQualifiedName(program.Project.RootNamespace)}.__EplGlobals;");
        writer.WriteLine();

        using (writer.Block($"namespace {NormalizeQualifiedName(program.Project.RootNamespace)}"))
        {
            EmitGlobals(writer);
            foreach (DeclarationSyntax declaration in program.Declarations)
            {
                switch (declaration)
                {
                    case ClassDeclarationSyntax @class:
                        EmitClass(writer, @class);
                        break;
                    case StructDeclarationSyntax structure:
                        EmitStruct(writer, structure);
                        break;
                    case EnumDeclarationSyntax enumeration:
                        EmitEnum(writer, enumeration);
                        break;
                }
            }
        }

        return writer.ToString();
    }

    private void EmitGlobals(IndentedWriter writer)
    {
        using (writer.Block("internal static class __EplGlobals"))
        {
            foreach (DeclarationSyntax declaration in program.Declarations)
            {
                switch (declaration)
                {
                    case FieldDeclarationSyntax field:
                        EmitField(writer, field, forceStatic: true);
                        break;
                    case ConstantDeclarationSyntax constant:
                        LineDirective(writer, constant.Span);
                        writer.WriteLine($"{VisibilityText(constant.Visibility)} static readonly {InferConstantType(constant.Value)} {Identifier(constant.Name)} = {EmitExpression(constant.Value)};");
                        ResetLineDirective(writer);
                        break;
                    case DllDeclarationSyntax dll:
                        EmitDll(writer, dll);
                        break;
                }
            }
        }
        writer.WriteLine();
    }

    private void EmitClass(IndentedWriter writer, ClassDeclarationSyntax @class)
    {
        currentClass = @class;
        string modifiers = DeclarationModifiersText(@class.Modifiers & (DeclarationModifiers.Abstract | DeclarationModifiers.Sealed | DeclarationModifiers.Partial));
        string baseType = @class.BaseType is null ? string.Empty : $" : {TypeText(@class.BaseType)}";
        string visibility = program.Plugin?.ConfigClassName?.Equals(@class.Name, StringComparison.OrdinalIgnoreCase) == true
            ? "public"
            : VisibilityText(@class.Visibility);
        LineDirective(writer, @class.Span);
        using (writer.Block($"{visibility} {modifiers}class {Identifier(@class.Name)}{baseType}".Replace("  ", " ")))
        {
            foreach (FieldDeclarationSyntax field in @class.Fields)
                EmitField(writer, field);

            Dictionary<MethodDeclarationSyntax, Dictionary<string, string>> hoistedByMethod = new();
            int hoistedOrdinal = 0;
            foreach (MethodDeclarationSyntax method in @class.Methods)
            {
                Dictionary<string, string> methodHoisted = new(StringComparer.OrdinalIgnoreCase);
                foreach (LocalVariableSyntax local in method.Locals.Where(static local => local.Modifiers.HasFlag(DeclarationModifiers.Static)))
                {
                    string fieldName = $"__静态_{Identifier(method.Name).TrimStart('@')}_{Identifier(local.Name).TrimStart('@')}_{++hoistedOrdinal}";
                    methodHoisted[local.Name] = fieldName;
                    bool lazyInitialize = NeedsLazyHoistedInitialization(local);
                    string initializer = !lazyInitialize
                        ? EmitInitializer(local.Type, local.ArrayShape, null)
                        : " = default!";
                    writer.WriteLine($"private static {TypeText(local.Type, local.ArrayShape is not null)} {fieldName}{initializer};");
                    if (lazyInitialize)
                        writer.WriteLine($"private static bool {HoistedInitializerFlag(fieldName)};");
                }
                hoistedByMethod[method] = methodHoisted;
            }

            if (@class.Fields.Count > 0 || hoistedByMethod.Values.Any(static map => map.Count > 0))
                writer.WriteLine();

            foreach (MethodDeclarationSyntax method in @class.Methods)
            {
                hoistedLocals = hoistedByMethod[method];
                EmitMethod(writer, method, @class.Name);
                writer.WriteLine();
            }
        }
        ResetLineDirective(writer);
        writer.WriteLine();
        currentClass = null;
        hoistedLocals = new Dictionary<string, string>();
    }

    private void EmitStruct(IndentedWriter writer, StructDeclarationSyntax structure)
    {
        LineDirective(writer, structure.Span);
        using (writer.Block($"{VisibilityText(structure.Visibility)} struct {Identifier(structure.Name)}"))
        {
            foreach (FieldDeclarationSyntax member in structure.Members)
                EmitField(writer, member);
        }
        ResetLineDirective(writer);
        writer.WriteLine();
    }

    private void EmitEnum(IndentedWriter writer, EnumDeclarationSyntax enumeration)
    {
        LineDirective(writer, enumeration.Span);
        using (writer.Block($"{VisibilityText(enumeration.Visibility)} enum {Identifier(enumeration.Name)}"))
        {
            foreach (EnumMemberSyntax member in enumeration.Members)
            {
                string value = member.Value is null ? string.Empty : $" = {EmitExpression(member.Value)}";
                writer.WriteLine($"{Identifier(member.Name)}{value},");
            }
        }
        ResetLineDirective(writer);
        writer.WriteLine();
    }

    private void EmitField(IndentedWriter writer, FieldDeclarationSyntax field, bool forceStatic = false)
    {
        LineDirective(writer, field.Span);
        DeclarationModifiers modifiers = field.Modifiers;
        if (forceStatic)
            modifiers |= DeclarationModifiers.Static;
        string modifierText = DeclarationModifiersText(modifiers & (DeclarationModifiers.Static | DeclarationModifiers.ReadOnly));
        writer.WriteLine($"{VisibilityText(field.Visibility)} {modifierText}{TypeText(field.Type, field.ArrayShape is not null)} {Identifier(field.Name)}{EmitInitializer(field.Type, field.ArrayShape, field.Initializer)};".Replace("  ", " "));
        ResetLineDirective(writer);
    }

    private void EmitDll(IndentedWriter writer, DllDeclarationSyntax dll)
    {
        LineDirective(writer, dll.Span);
        writer.WriteLine($"[System.Runtime.InteropServices.DllImport({StringLiteral(dll.LibraryName)}, EntryPoint = {StringLiteral(dll.EntryPoint)})]");
        writer.WriteLine($"{VisibilityText(dll.Visibility)} static extern {TypeText(dll.ReturnType)} {Identifier(dll.Name)}({string.Join(", ", dll.Parameters.Select(EmitParameter))});");
        ResetLineDirective(writer);
    }

    private void EmitMethod(IndentedWriter writer, MethodDeclarationSyntax method, string className)
    {
        currentMethod = method;
        LineDirective(writer, method.Span);
        bool constructor = method.Modifiers.HasFlag(DeclarationModifiers.Constructor) || method.Name == "_初始化";
        string signature;
        if (constructor)
        {
            signature = $"{MethodVisibilityText(method)} {Identifier(className)}({string.Join(", ", method.Parameters.Select(EmitParameter))})";
        }
        else
        {
            string modifiers = DeclarationModifiersText(method.Modifiers & ~DeclarationModifiers.Constructor);
            signature = $"{MethodVisibilityText(method)} {modifiers}{TypeText(method.ReturnType)} {Identifier(method.Name)}({string.Join(", ", method.Parameters.Select(EmitParameter))})".Replace("  ", " ");
        }

        using (writer.Block(signature))
        {
            foreach (LocalVariableSyntax local in method.Locals.Where(static local => !local.Modifiers.HasFlag(DeclarationModifiers.Static)))
            {
                LineDirective(writer, local.Span);
                writer.WriteLine($"{TypeText(local.Type, local.ArrayShape is not null)} {Identifier(local.Name)}{EmitInitializer(local.Type, local.ArrayShape, local.Initializer)};");
            }

            foreach (LocalVariableSyntax local in method.Locals.Where(static local => local.Modifiers.HasFlag(DeclarationModifiers.Static) && NeedsLazyHoistedInitialization(local)))
            {
                string fieldName = hoistedLocals[local.Name];
                LineDirective(writer, local.Span);
                using (writer.Block($"if (!{HoistedInitializerFlag(fieldName)})"))
                {
                    writer.WriteLine($"{fieldName} = {EmitLazyHoistedInitialValue(local)};");
                    writer.WriteLine($"{HoistedInitializerFlag(fieldName)} = true;");
                }
            }

            foreach (StatementSyntax statement in method.Statements)
                EmitStatement(writer, statement);

            if (!constructor && TypeText(method.ReturnType) != "void" && !DefinitelyReturns(method.Statements))
                writer.WriteLine($"return {DefaultValue(method.ReturnType)};");
        }
        ResetLineDirective(writer);
        currentMethod = null;
    }

    private void EmitStatement(IndentedWriter writer, StatementSyntax statement)
    {
        LineDirective(writer, statement.Span);
        switch (statement)
        {
            case EmptyStatementSyntax:
                writer.WriteLine();
                break;

            case AssignmentStatementSyntax assignment:
                TypeSyntax? assignmentType = ResolveExpressionType(assignment.Target);
                writer.WriteLine($"{EmitExpression(assignment.Target)} = {EmitExpressionForDestination(assignmentType, assignment.Value)};");
                break;

            case ExpressionStatementSyntax expression:
                EmitExpressionStatement(writer, expression.Expression);
                break;

            case IfStatementSyntax conditional:
                using (writer.Block($"if ({EmitExpression(conditional.Condition)})"))
                    foreach (StatementSyntax child in conditional.ThenStatements) EmitStatement(writer, child);
                if (conditional.ElseStatements.Count > 0)
                {
                    using (writer.Block("else"))
                        foreach (StatementSyntax child in conditional.ElseStatements) EmitStatement(writer, child);
                }
                break;

            case WhileStatementSyntax loop when loop.TestAfterBody:
                writer.WriteLine("do");
                writer.WriteLine("{");
                writer.Indent();
                foreach (StatementSyntax child in loop.Statements) EmitStatement(writer, child);
                writer.Unindent();
                writer.WriteLine($"}} while ({EmitExpression(loop.Condition)});");
                break;

            case WhileStatementSyntax loop:
                using (writer.Block($"while ({EmitExpression(loop.Condition)})"))
                    foreach (StatementSyntax child in loop.Statements) EmitStatement(writer, child);
                break;

            case CountLoopStatementSyntax count:
                EmitCountLoop(writer, count);
                break;

            case RangeLoopStatementSyntax range:
                EmitRangeLoop(writer, range);
                break;

            case ForEachStatementSyntax each:
                string eachType = each.VariableType is null ? "var" : TypeText(each.VariableType);
                using (writer.Block($"foreach ({eachType} {Identifier(each.VariableName)} in {EmitExpression(each.Collection)})"))
                    foreach (StatementSyntax child in each.Statements) EmitStatement(writer, child);
                break;

            case ChooseStatementSyntax choose:
                if (choose.Branches.Count == 0)
                {
                    // A default-only Easy choice is an unconditional block. Emitting
                    // `else` without a preceding `if` would produce invalid C#.
                    foreach (StatementSyntax child in choose.DefaultStatements) EmitStatement(writer, child);
                    break;
                }

                for (int i = 0; i < choose.Branches.Count; i++)
                {
                    ConditionalBranchSyntax branch = choose.Branches[i];
                    using (writer.Block($"{(i == 0 ? "if" : "else if")} ({EmitExpression(branch.Condition)})"))
                        foreach (StatementSyntax child in branch.Statements) EmitStatement(writer, child);
                }
                if (choose.DefaultStatements.Count > 0)
                {
                    using (writer.Block("else"))
                        foreach (StatementSyntax child in choose.DefaultStatements) EmitStatement(writer, child);
                }
                break;

            case TryStatementSyntax attempt:
                if (attempt.Catches.Count == 0 && attempt.FinallyStatements.Count == 0)
                {
                    // A handler-free try has no observable exception behavior of its
                    // own, so EPLab treats it as a grouping block. This also covers an
                    // explicitly empty `.\u6700\u7ec8` block, which is behaviorally identical.
                    foreach (StatementSyntax child in attempt.TryStatements) EmitStatement(writer, child);
                    break;
                }

                using (writer.Block("try"))
                    foreach (StatementSyntax child in attempt.TryStatements) EmitStatement(writer, child);
                foreach (CatchClauseSyntax clause in attempt.Catches)
                {
                    using (writer.Block($"catch ({TypeText(clause.ExceptionType)} {Identifier(clause.VariableName)})"))
                        foreach (StatementSyntax child in clause.Statements) EmitStatement(writer, child);
                }
                if (attempt.FinallyStatements.Count > 0)
                {
                    using (writer.Block("finally"))
                        foreach (StatementSyntax child in attempt.FinallyStatements) EmitStatement(writer, child);
                }
                break;

            case TemporarySetStatementSyntax temporary:
                EmitTemporarySet(writer, temporary);
                break;

            case LockStatementSyntax locked:
                using (writer.Block($"lock ({EmitExpression(locked.Target)})"))
                    foreach (StatementSyntax child in locked.Statements) EmitStatement(writer, child);
                break;

            case UsingStatementSyntax resource:
                using (writer.Block($"using (var {Identifier(resource.VariableName)} = {EmitExpression(resource.Value)})"))
                    foreach (StatementSyntax child in resource.Statements) EmitStatement(writer, child);
                break;

            default:
                writer.WriteLine($"throw new System.NotSupportedException({StringLiteral($"Unsupported EPLab statement: {statement.GetType().Name}")});");
                break;
        }
    }

    private void EmitExpressionStatement(IndentedWriter writer, ExpressionSyntax expression)
    {
        if (expression is CallExpressionSyntax { Target: NameExpressionSyntax name } call)
        {
            string normalized = name.Name.ToUpperInvariant();
            if (normalized is "返回" or "RETURN")
            {
                writer.WriteLine(call.Arguments.Count == 0 || call.Arguments[0].Value is MissingExpressionSyntax
                    ? "return;"
                    : $"return {EmitExpressionForDestination(currentMethod?.ReturnType, call.Arguments[0].Value)};");
                return;
            }
            if (normalized is "跳出循环" or "BREAK")
            {
                writer.WriteLine("break;");
                return;
            }
            if (normalized is "到循环尾" or "CONTINUE")
            {
                writer.WriteLine("continue;");
                return;
            }
            if (normalized is "抛出" or "THROW")
            {
                writer.WriteLine($"throw {EmitExpression(call.Arguments.FirstOrDefault()?.Value ?? new NewExpressionSyntax(new TypeSyntax("Exception", false, false, expression.Span), Array.Empty<ArgumentSyntax>(), expression.Span))};");
                return;
            }
            if (normalized is "重定义数组")
            {
                if (call.Arguments.Count >= 2)
                {
                    string target = EmitExpression(call.Arguments[0].Value);
                    string dimensions = string.Join(", ", call.Arguments.Skip(1).Select(argument => EmitExpression(argument.Value)));
                    writer.WriteLine($"{target}.Redim({dimensions});");
                }
                return;
            }

            if (normalized is "转换类型" or "CAST" or "安全转换类型" or "CHECKEDCAST"
                or "是否类型" or "IS" or "默认值" or "DEFAULT" or "选择" or "IIF"
                or "字符" or "到文本" or "取数组成员数" or "取文本长度" or "是否为空"
                or "到CLR数组" or "TOCLRARRAY" or "从CLR数组" or "FROMCLRARRAY")
            {
                writer.WriteLine($"global::System.GC.KeepAlive({EmitExpression(expression)});");
                return;
            }
        }

        if (expression is CallExpressionSyntax or NewExpressionSyntax)
            writer.WriteLine($"{EmitExpression(expression)};");
        else
            writer.WriteLine($"global::System.GC.KeepAlive({EmitExpression(expression)});");
    }

    private void EmitCountLoop(IndentedWriter writer, CountLoopStatementSyntax count)
    {
        string limit = Fresh("count");
        string counter = count.Counter is null ? Fresh("i") : EmitExpression(count.Counter);
        writer.WriteLine($"int {limit} = System.Convert.ToInt32({EmitExpression(count.Count)}, System.Globalization.CultureInfo.InvariantCulture);");
        using (writer.Block($"for ({(count.Counter is null ? "int " : string.Empty)}{counter} = 1; {counter} <= {limit}; {counter}++)"))
            foreach (StatementSyntax child in count.Statements) EmitStatement(writer, child);
    }

    private void EmitRangeLoop(IndentedWriter writer, RangeLoopStatementSyntax range)
    {
        string end = Fresh("end");
        string step = Fresh("step");
        string variable = range.Variable is null ? Fresh("value") : EmitExpression(range.Variable);
        TypeSyntax variableType = range.Variable is null
            ? new TypeSyntax("双精度小数型", false, false, range.Span)
            : ResolveExpressionType(range.Variable) ?? new TypeSyntax("双精度小数型", false, false, range.Span);
        string type = TypeText(variableType);
        string startValue = $"unchecked(({type})({EmitExpression(range.Start)}))";
        string endValue = $"unchecked(({type})({EmitExpression(range.End)}))";
        string stepValue = $"unchecked(({type})({EmitExpression(range.Step ?? new LiteralExpressionSyntax(1L, "1", range.Span))}))";
        writer.WriteLine($"{type} {end} = {endValue};");
        writer.WriteLine($"{type} {step} = {stepValue};");
        writer.WriteLine($"if ({step} == 0) throw new global::System.ArgumentOutOfRangeException(\"step\", \"变量循环步长不能为零。\");");
        string increment = $"{variable} = unchecked(({type})({variable} + {step}))";
        using (writer.Block($"for ({(range.Variable is null ? type + " " : string.Empty)}{variable} = {startValue}; {step} >= 0 ? {variable} <= {end} : {variable} >= {end}; {increment})"))
            foreach (StatementSyntax child in range.Statements) EmitStatement(writer, child);
    }

    private void EmitTemporarySet(IndentedWriter writer, TemporarySetStatementSyntax temporary)
    {
        string target = EmitExpression(temporary.Target);
        string old = Fresh("old");
        writer.WriteLine($"var {old} = {target};");
        writer.WriteLine("try");
        writer.WriteLine("{");
        writer.Indent();
        writer.WriteLine($"{target} = {EmitExpression(temporary.Value)};");
        foreach (StatementSyntax child in temporary.Statements) EmitStatement(writer, child);
        writer.Unindent();
        writer.WriteLine("}");
        writer.WriteLine("finally");
        writer.WriteLine("{");
        writer.Indent();
        writer.WriteLine($"{target} = {old};");
        writer.Unindent();
        writer.WriteLine("}");
    }

    private string EmitExpression(ExpressionSyntax expression) => expression switch
    {
        MissingExpressionSyntax => "default",
        LiteralExpressionSyntax literal => EmitLiteral(literal),
        InterpolatedStringExpressionSyntax interpolated => EmitInterpolatedString(interpolated),
        NameExpressionSyntax name => EmitName(name.Name),
        ConstantExpressionSyntax constant => EmitConstant(constant),
        UnaryExpressionSyntax unary => $"({unary.Operator}{EmitExpression(unary.Operand)})",
        BinaryExpressionSyntax { Operator: "~=" } binary => $"global::EPLab.Runtime.EplRuntime.ApproximatelyEqual({EmitExpression(binary.Left)}, {EmitExpression(binary.Right)})",
        BinaryExpressionSyntax { Operator: "\\" } binary => $"({EmitExpression(binary.Left)} / {EmitExpression(binary.Right)})",
        BinaryExpressionSyntax binary => $"({EmitExpression(binary.Left)} {binary.Operator} {EmitExpression(binary.Right)})",
        MemberAccessExpressionSyntax member => $"{EmitExpression(member.Target)}{(member.NullConditional ? "?." : ".")}{EmitMemberName(member.MemberName, member.Target)}",
        CallExpressionSyntax call => EmitCall(call),
        IndexExpressionSyntax index => $"{EmitExpression(index.Target)}[{string.Join(", ", index.Indices.Select(EmitExpression))}]",
        ArrayLiteralExpressionSyntax array => EmitArrayLiteral(array),
        DelegateExpressionSyntax method => Identifier(ResolveDeclaredValueName(method.MethodName) ?? method.MethodName),
        TypeTestExpressionSyntax test => $"({EmitExpression(test.Value)} is {(test.Negated ? "not " : string.Empty)}{TypeText(test.Type)})",
        ConversionExpressionSyntax conversion => $"(({TypeText(conversion.Type)}){EmitExpression(conversion.Value)})",
        NewExpressionSyntax creation => $"new {TypeText(creation.Type)}({string.Join(", ", creation.Arguments.Select(EmitArgument))})",
        _ => "default",
    };

    private string EmitLiteral(LiteralExpressionSyntax literal)
    {
        if (literal.Value is null)
            return "null";
        if (literal.Value is bool boolean)
            return boolean ? "true" : "false";
        if (literal.Value is long integer)
        {
            string text = integer.ToString(CultureInfo.InvariantCulture);
            bool forcedLong = literal.RawText.EndsWith("L", StringComparison.OrdinalIgnoreCase)
                && !literal.RawText.EndsWith("UL", StringComparison.OrdinalIgnoreCase);
            return forcedLong || integer is > int.MaxValue or < int.MinValue ? text + "L" : text;
        }
        if (literal.Value is uint unsignedInteger)
            return unsignedInteger.ToString(CultureInfo.InvariantCulture) + "U";
        if (literal.Value is ulong unsignedLong)
            return unsignedLong.ToString(CultureInfo.InvariantCulture) + "UL";
        if (literal.Value is float single)
        {
            if (float.IsNaN(single)) return "float.NaN";
            if (float.IsPositiveInfinity(single)) return "float.PositiveInfinity";
            if (float.IsNegativeInfinity(single)) return "float.NegativeInfinity";
            return single.ToString("R", CultureInfo.InvariantCulture) + "F";
        }
        if (literal.Value is double number)
        {
            if (double.IsNaN(number)) return "double.NaN";
            if (double.IsPositiveInfinity(number)) return "double.PositiveInfinity";
            if (double.IsNegativeInfinity(number)) return "double.NegativeInfinity";
            return number.ToString("R", CultureInfo.InvariantCulture) + "D";
        }
        if (literal.RawText.StartsWith('['))
            return $"global::EPLab.Runtime.EplRuntime.ParseDateTime({StringLiteral(literal.RawText)})";
        return StringLiteral(Convert.ToString(literal.Value, CultureInfo.InvariantCulture) ?? string.Empty);
    }

    private string EmitInterpolatedString(InterpolatedStringExpressionSyntax interpolated)
    {
        StringBuilder result = new("$\"");
        foreach (InterpolatedPartSyntax part in interpolated.Parts)
        {
            if (part is InterpolatedTextSyntax text)
            {
                AppendInterpolatedText(result, text.Text);
                continue;
            }
            if (part is InterpolationSyntax hole)
                result.Append('{').Append(EmitExpression(hole.Expression))
                    .Append(hole.Format is null ? string.Empty : ":" + hole.Format).Append('}');
        }
        result.Append('"');
        return result.ToString();
    }

    private static void AppendInterpolatedText(StringBuilder result, string value)
    {
        result.Append(value
            .Replace("\\", "\\\\", StringComparison.Ordinal)
            .Replace("\"", "\\\"", StringComparison.Ordinal)
            .Replace("\r", "\\r", StringComparison.Ordinal)
            .Replace("\n", "\\n", StringComparison.Ordinal)
            .Replace("{", "{{", StringComparison.Ordinal)
            .Replace("}", "}}", StringComparison.Ordinal));
    }

    private string EmitCall(CallExpressionSyntax call)
    {
        if (call.Target is NameExpressionSyntax name)
        {
            string normalized = name.Name.ToUpperInvariant();
            if (normalized is "创建对象" or "NEW")
            {
                if (call.Arguments.Count == 0)
                    return "new object()";
                string type = ExpressionAsType(call.Arguments[0].Value);
                return $"new {type}({string.Join(", ", call.Arguments.Skip(1).Select(EmitArgument))})";
            }
            if (normalized is "转换类型" or "CAST")
            {
                if (call.Arguments.Count < 2) return "default";
                return $"unchecked(({ExpressionAsType(call.Arguments[0].Value)})({EmitExpression(call.Arguments[1].Value)}))";
            }
            if (normalized is "安全转换类型" or "CHECKEDCAST")
            {
                if (call.Arguments.Count < 2) return "default";
                return $"checked(({ExpressionAsType(call.Arguments[0].Value)})({EmitExpression(call.Arguments[1].Value)}))";
            }
            if (normalized is "是否类型" or "IS")
            {
                if (call.Arguments.Count < 2) return "false";
                return $"({EmitExpression(call.Arguments[0].Value)} is {ExpressionAsType(call.Arguments[1].Value)})";
            }
            if (normalized is "默认值" or "DEFAULT")
                return call.Arguments.Count == 0 ? "default" : $"default({ExpressionAsType(call.Arguments[0].Value)})";
            if (normalized is "选择" or "IIF")
            {
                if (call.Arguments.Count < 3) return "default";
                return $"({EmitExpression(call.Arguments[0].Value)} ? {EmitExpression(call.Arguments[1].Value)} : {EmitExpression(call.Arguments[2].Value)})";
            }
            if (normalized is "字符")
                return call.Arguments.Count == 0 ? "string.Empty" : $"global::System.Convert.ToChar({EmitExpression(call.Arguments[0].Value)}).ToString()";
            if (normalized is "到文本")
                return call.Arguments.Count == 0 ? "string.Empty" : $"global::System.Convert.ToString({EmitExpression(call.Arguments[0].Value)}, global::System.Globalization.CultureInfo.InvariantCulture) ?? string.Empty";
            if (normalized is "取数组成员数")
                return call.Arguments.Count == 0 ? "0" : $"{EmitExpression(call.Arguments[0].Value)}.Count";
            if (normalized is "取文本长度")
                return call.Arguments.Count == 0 ? "0" : $"{EmitExpression(call.Arguments[0].Value)}.Length";
            if (normalized is "是否为空")
                return call.Arguments.Count == 0 ? "true" : $"global::EPLab.Runtime.EplRuntime.IsMissing({EmitExpression(call.Arguments[0].Value)})";
            if (normalized is "到CLR数组" or "TOCLRARRAY")
                return call.Arguments.Count == 0 ? "global::System.Array.Empty<object>()" : $"{EmitExpression(call.Arguments[0].Value)}.ToArray()";
            if (normalized is "从CLR数组" or "FROMCLRARRAY")
                return call.Arguments.Count == 0 ? "new global::EPLab.Runtime.EArray<object>()" : $"global::EPLab.Runtime.EplRuntime.ArrayFrom({EmitExpression(call.Arguments[0].Value)})";
        }

        return $"{EmitExpression(call.Target)}({string.Join(", ", call.Arguments.Select(EmitArgument))})";
    }

    private string EmitArgument(ArgumentSyntax argument)
    {
        string prefix = argument.Modifiers.HasFlag(ParameterModifiers.Out)
            ? "out "
            : argument.Modifiers.HasFlag(ParameterModifiers.ByReference) ? "ref " : string.Empty;
        string name = argument.Name is null ? string.Empty : $"{Identifier(argument.Name)}: ";
        return $"{name}{prefix}{EmitExpression(argument.Value)}";
    }

    private string EmitName(string name)
    {
        if (hoistedLocals.TryGetValue(name, out string? hoisted))
            return hoisted;
        string? declaredName = ResolveDeclaredValueName(name);
        if (declaredName is not null)
            return Identifier(declaredName);
        return name.ToUpperInvariant() switch
        {
            "日志" when program.Plugin is not null => "global::LabApi.Features.Console.Logger",
            "配置" when program.Plugin is not null => "global::__EplabHost.Config",
            "环境" => "global::System.Environment",
            _ => NormalizeQualifiedName(name),
        };
    }

    private string? ResolveDeclaredValueName(string name)
    {
        LocalVariableSyntax? local = currentMethod?.Locals.FirstOrDefault(item => item.Name.Equals(name, StringComparison.OrdinalIgnoreCase));
        if (local is not null) return local.Name;
        ParameterSyntax? parameter = currentMethod?.Parameters.FirstOrDefault(item => item.Name.Equals(name, StringComparison.OrdinalIgnoreCase));
        if (parameter is not null) return parameter.Name;
        FieldDeclarationSyntax? field = currentClass?.Fields.FirstOrDefault(item => item.Name.Equals(name, StringComparison.OrdinalIgnoreCase));
        if (field is not null) return field.Name;
        MethodDeclarationSyntax? method = currentClass?.Methods.FirstOrDefault(item => item.Name.Equals(name, StringComparison.OrdinalIgnoreCase));
        if (method is not null) return method.Name;
        return program.Declarations.Select(declaration => declaration switch
        {
            FieldDeclarationSyntax global when global.Name.Equals(name, StringComparison.OrdinalIgnoreCase) => global.Name,
            ConstantDeclarationSyntax constant when constant.Name.Equals(name, StringComparison.OrdinalIgnoreCase) => constant.Name,
            DllDeclarationSyntax dll when dll.Name.Equals(name, StringComparison.OrdinalIgnoreCase) => dll.Name,
            ClassDeclarationSyntax @class when @class.Name.Equals(name, StringComparison.OrdinalIgnoreCase) => @class.Name,
            StructDeclarationSyntax structure when structure.Name.Equals(name, StringComparison.OrdinalIgnoreCase) => structure.Name,
            EnumDeclarationSyntax enumeration when enumeration.Name.Equals(name, StringComparison.OrdinalIgnoreCase) => enumeration.Name,
            _ => null,
        }).FirstOrDefault(static item => item is not null);
    }

