            "日期时间型" or "DATETIME" => "global::System.DateTime",
            "通用型" or "OBJECT" => "object",
            "子程序指针" or "DELEGATE" => "global::System.Delegate",
            "命令上下文" or "COMMANDCONTEXT" or "EPLAB.RUNTIME.COMMANDCONTEXT" => "global::EPLab.Runtime.CommandContext",
            "列表" or "LIST" => "global::System.Collections.Generic.List",
            "字典" or "DICTIONARY" => "global::System.Collections.Generic.Dictionary",
