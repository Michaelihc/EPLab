    private string InferConstantType(ExpressionSyntax expression) => expression switch
    {
        LiteralExpressionSyntax { Value: bool } => "bool",
        LiteralExpressionSyntax { Value: long, RawText: var raw } when raw.EndsWith("L", StringComparison.OrdinalIgnoreCase) => "long",
        LiteralExpressionSyntax { Value: long value } => value is <= int.MaxValue and >= int.MinValue ? "int" : "long",
        LiteralExpressionSyntax { Value: uint } => "uint",
        LiteralExpressionSyntax { Value: ulong } => "ulong",
        LiteralExpressionSyntax { Value: float } => "float",
        LiteralExpressionSyntax { Value: double } => "double",
        LiteralExpressionSyntax { Value: string, RawText: var raw } when raw.StartsWith('[') => "global::System.DateTime",
        LiteralExpressionSyntax { Value: string } => "string",
        ConstantExpressionSyntax { TypeName: not null } constant => TypeNameText(constant.TypeName!),
        _ => "dynamic",
    };

    private TypeSyntax? ResolveExpressionType(ExpressionSyntax expression)
    {
        switch (expression)
        {
            case NameExpressionSyntax name:
                LocalVariableSyntax? local = currentMethod?.Locals.FirstOrDefault(item => item.Name.Equals(name.Name, StringComparison.OrdinalIgnoreCase));
                if (local is not null) return local.Type with { IsArray = local.ArrayShape is not null || local.Type.IsArray };
                ParameterSyntax? parameter = currentMethod?.Parameters.FirstOrDefault(item => item.Name.Equals(name.Name, StringComparison.OrdinalIgnoreCase));
                if (parameter is not null) return parameter.Type with { IsArray = parameter.Type.IsArray || parameter.Modifiers.HasFlag(ParameterModifiers.Array) };
                FieldDeclarationSyntax? field = currentClass?.Fields.FirstOrDefault(item => item.Name.Equals(name.Name, StringComparison.OrdinalIgnoreCase));
                if (field is not null) return field.Type with { IsArray = field.ArrayShape is not null || field.Type.IsArray };
                FieldDeclarationSyntax? global = program.Declarations.OfType<FieldDeclarationSyntax>()
                    .FirstOrDefault(item => item.Name.Equals(name.Name, StringComparison.OrdinalIgnoreCase));
                if (global is not null) return global.Type with { IsArray = global.ArrayShape is not null || global.Type.IsArray };
                string? declaredTypeName = ResolveUserDeclaredTypeName(name.Name);
                if (declaredTypeName is not null) return new TypeSyntax(declaredTypeName, false, false, name.Span);
                return null;

            case LiteralExpressionSyntax { Value: bool } literal:
                return new TypeSyntax("逻辑型", false, false, literal.Span);
            case LiteralExpressionSyntax { Value: long } literal:
                return new TypeSyntax("长整数型", false, false, literal.Span);
            case LiteralExpressionSyntax { Value: uint } literal:
                return new TypeSyntax("无符号整数型", false, false, literal.Span);
            case LiteralExpressionSyntax { Value: float } literal:
                return new TypeSyntax("小数型", false, false, literal.Span);
            case LiteralExpressionSyntax { Value: double } literal:
                return new TypeSyntax("双精度小数型", false, false, literal.Span);
            case LiteralExpressionSyntax { Value: string } literal:
                return new TypeSyntax("文本型", false, false, literal.Span);
            case InterpolatedStringExpressionSyntax interpolated:
                return new TypeSyntax("文本型", false, false, interpolated.Span);
            case ConversionExpressionSyntax conversion:
                return conversion.Type;
            case NewExpressionSyntax creation:
                return creation.Type;
            case IndexExpressionSyntax index:
                TypeSyntax? indexed = ResolveExpressionType(index.Target);
                return indexed is null ? null : indexed with { IsArray = false };
            case MemberAccessExpressionSyntax member:
                TypeSyntax? receiver = ResolveExpressionType(member.Target);
                return receiver is null ? null : ResolveUserMemberType(receiver.Text, member.MemberName);
            case CallExpressionSyntax { Target: NameExpressionSyntax callName } call:
                if (callName.Name.Equals("创建对象", StringComparison.OrdinalIgnoreCase) && call.Arguments.Count > 0)
                {
                    string typeName = call.Arguments[0].Value switch
                    {
                        NameExpressionSyntax type => type.Name,
                        LiteralExpressionSyntax { Value: string text } => text,
                        _ => string.Empty,
                    };
                    return typeName.Length == 0 ? null : new TypeSyntax(typeName, false, false, call.Span);
                }
                return currentClass?.Methods.FirstOrDefault(method => method.Name.Equals(callName.Name, StringComparison.OrdinalIgnoreCase))?.ReturnType;
            case CallExpressionSyntax { Target: MemberAccessExpressionSyntax memberCall }:
                TypeSyntax? callReceiver = ResolveExpressionType(memberCall.Target);
                return callReceiver is null ? null : ResolveUserMethodType(callReceiver.Text, memberCall.MemberName);
            default:
                return null;
        }
    }

    private TypeSyntax? ResolveUserMemberType(string typeName, string memberName)
    {
        ClassDeclarationSyntax? @class = program.Declarations.OfType<ClassDeclarationSyntax>()
            .FirstOrDefault(item => item.Name.Equals(typeName, StringComparison.OrdinalIgnoreCase));
        FieldDeclarationSyntax? field = @class?.Fields.FirstOrDefault(item => item.Name.Equals(memberName, StringComparison.OrdinalIgnoreCase));
        if (field is not null) return field.Type with { IsArray = field.ArrayShape is not null || field.Type.IsArray };
        StructDeclarationSyntax? structure = program.Declarations.OfType<StructDeclarationSyntax>()
            .FirstOrDefault(item => item.Name.Equals(typeName, StringComparison.OrdinalIgnoreCase));
        FieldDeclarationSyntax? member = structure?.Members.FirstOrDefault(item => item.Name.Equals(memberName, StringComparison.OrdinalIgnoreCase));
        return member?.Type;
    }

    private TypeSyntax? ResolveUserMethodType(string typeName, string methodName)
        => program.Declarations.OfType<ClassDeclarationSyntax>()
            .FirstOrDefault(item => item.Name.Equals(typeName, StringComparison.OrdinalIgnoreCase))?
            .Methods.FirstOrDefault(item => item.Name.Equals(methodName, StringComparison.OrdinalIgnoreCase))?
            .ReturnType;

    private string? ResolveUserMemberName(string typeName, string memberName)
    {
        ClassDeclarationSyntax? @class = program.Declarations.OfType<ClassDeclarationSyntax>()
            .FirstOrDefault(item => item.Name.Equals(typeName, StringComparison.OrdinalIgnoreCase));
        if (@class is not null)
        {
            FieldDeclarationSyntax? field = @class.Fields.FirstOrDefault(item => item.Name.Equals(memberName, StringComparison.OrdinalIgnoreCase));
            if (field is not null) return field.Name;
            MethodDeclarationSyntax? method = @class.Methods.FirstOrDefault(item => item.Name.Equals(memberName, StringComparison.OrdinalIgnoreCase));
            if (method is not null) return method.Name;
        }

        StructDeclarationSyntax? structure = program.Declarations.OfType<StructDeclarationSyntax>()
            .FirstOrDefault(item => item.Name.Equals(typeName, StringComparison.OrdinalIgnoreCase));
        FieldDeclarationSyntax? structureMember = structure?.Members
            .FirstOrDefault(item => item.Name.Equals(memberName, StringComparison.OrdinalIgnoreCase));
        if (structureMember is not null) return structureMember.Name;

        EnumDeclarationSyntax? enumeration = program.Declarations.OfType<EnumDeclarationSyntax>()
            .FirstOrDefault(item => item.Name.Equals(typeName, StringComparison.OrdinalIgnoreCase));
        return enumeration?.Members.FirstOrDefault(item => item.Name.Equals(memberName, StringComparison.OrdinalIgnoreCase))?.Name;
    }

    private string? ResolveUserDeclaredTypeName(string typeName)
    {
        int generic = typeName.IndexOf('<');
        if (generic >= 0) typeName = typeName[..generic];
        return program.Declarations.Select(declaration => declaration switch
        {
            ClassDeclarationSyntax @class when @class.Name.Equals(typeName, StringComparison.OrdinalIgnoreCase) => @class.Name,
            StructDeclarationSyntax structure when structure.Name.Equals(typeName, StringComparison.OrdinalIgnoreCase) => structure.Name,
            EnumDeclarationSyntax enumeration when enumeration.Name.Equals(typeName, StringComparison.OrdinalIgnoreCase) => enumeration.Name,
            _ => null,
        }).FirstOrDefault(static item => item is not null);
    }

    private bool IsUserDeclaredType(string typeName) => ResolveUserDeclaredTypeName(typeName) is not null;

