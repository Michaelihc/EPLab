                || value[..genericStart].Trim().Equals("CLRARRAY", StringComparison.OrdinalIgnoreCase))
                return arguments.Count == 1 ? TypeNameText(arguments[0]) + "[]" : "object[]";
            string outer = TypeNameText(value[..genericStart]);
            return $"{outer}<{string.Join(", ", arguments.Select(TypeNameText))}>";
        }
        string? declaredTypeName = ResolveUserDeclaredTypeName(value);
        if (declaredTypeName is not null)
            return NormalizeQualifiedName(declaredTypeName);
        return value.ToUpperInvariant() switch
        {
            "无返回值" or "VOID" => "void",
