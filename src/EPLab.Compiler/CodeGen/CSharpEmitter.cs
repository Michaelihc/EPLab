    }

    private string EmitConstant(ConstantExpressionSyntax constant)
    {
        if (constant.TypeName is not null)
        {
            string typeName = ResolveUserDeclaredTypeName(constant.TypeName) ?? constant.TypeName;
            string memberName = ResolveUserMemberName(typeName, constant.Name) ?? constant.Name;
            return $"{NormalizeQualifiedName(typeName)}.{Identifier(memberName)}";
        }
        return constant.Name switch
        {
            "换行符" => "global::System.Environment.NewLine",
