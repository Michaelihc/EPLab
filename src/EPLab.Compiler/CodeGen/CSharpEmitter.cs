        int start = 0;
        for (int i = 0; i < value.Length; i++)
        {
            if (value[i] == '<') nesting++;
            else if (value[i] == '>') nesting--;
            else if (value[i] == ',' && nesting == 0)
            {
                result.Add(value[start..i].Trim());
                start = i + 1;
            }
        }
        result.Add(value[start..].Trim());
        return result;
    }

